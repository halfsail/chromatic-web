  <h2>How to play</h2>

  <p>
    The board is a scrambled gradient. Move the tiles into their rightful place in the grid. Until the gradient is seamless and all the colors flow perfectly into one another.
  </p>
  <br>

    <p><strong>Locked tiles</strong> are already in their correct positions. Use them to figure out the surrounding colors.</p>
    <p><strong>Swap tiles</strong> by tapping or dragging any unlocked tile to another</p>
    <p><strong>Watch the gradient</strong> flow horizontally and vertically through hue, saturation, and brightness</p>

  <h3>Tips</h3>
  <p><strong>Start with the locked tiles.</strong> Try to find tiles that are just a shade lighter or darker than the locked ones and place them adjacent.</p>
  <p><strong>Check the Edges.</strong> It is often easiest to solve the outer edges of the grid first to establish the "frame" of the gradient.</p>
  <p><strong>Squint Your Eyes.</strong> If you’re stuck, try squinting at the screen. This helps your brain ignore the grid lines and see the overall flow of color more clearly.</p>
